const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const make = (tag) => ({tagName:tag.toUpperCase(), children:[], textContent:'', appendChild(child) { this.children.push(child); }});
const credit = make('p');
const figure = make('figure');
figure.querySelector = () => null;
const document = { getElementById:() => credit, createElement:make, createTextNode:text => ({textContent:text}) };
const context = vm.createContext({document,JSON});
vm.runInContext(fs.readFileSync('static/js/visuales.js','utf8'), context);
const backup = {src:'/static/img/referencias/plantas.jpg', nombre_confirmado:'Abarema barbouriana', autor:'Autor de respaldo', fuente_url:'https://example.org/foto', licencia:'Condiciones del autor', reference_label:'Imagen referencial del grupo · Plantas'};
const image = {dataset:{backup:JSON.stringify(backup),visualId:'E001'}, closest:() => figure};
context.ecoPhotoFailed(image);
assert.equal(image.src,backup.src);
assert.equal(figure.children[0].textContent,backup.reference_label);
assert.ok(credit.textContent.includes(backup.autor));
assert.equal(credit.children[0].href,backup.fuente_url);
image.onerror();
assert.equal(image.hidden,true);
console.log('Respaldo local, etiqueta y atribución actualizados al fallar una foto remota.');
